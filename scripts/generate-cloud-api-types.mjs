// Generates src/services/cloud-api/schema.d.ts from the vendored Laravel Cloud
// OpenAPI document. Run with `bun run api:types` after refreshing the contract
// (curl https://cloud.laravel.com/api-docs/api.json > contracts/laravel-cloud-openapi.json).
//
// The document has two quirks openapi-typescript cannot digest, so they are
// sanitised in memory first (the vendored file is left untouched):
//   - properties with an empty name ("") on some schemas
//   - `required` arrays that list `null` or "" for those properties
//   - discriminator mappings that point at schema names the document never defines
//     (the `oneOf` variants are inline, so the union types survive without them)
import { readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const SOURCE = new URL("../contracts/laravel-cloud-openapi.json", import.meta.url);
const TARGET = new URL("../src/services/cloud-api/schema.d.ts", import.meta.url);

function sanitise(node) {
  if (Array.isArray(node)) return node.map(sanitise);
  if (node === null || typeof node !== "object") return node;

  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "" || key === "discriminator") continue;
    if (key === "required" && Array.isArray(value)) {
      out[key] = value.filter((name) => typeof name === "string" && name !== "");
      continue;
    }
    out[key] = sanitise(value);
  }
  return out;
}

const spec = sanitise(JSON.parse(readFileSync(SOURCE, "utf8")));
const ast = await openapiTS(spec, { alphabetize: true });
const banner = `// Generated by scripts/generate-cloud-api-types.mjs from contracts/laravel-cloud-openapi.json.\n// Do not edit by hand; run \`bun run api:types\`.\n\n`;
writeFileSync(TARGET, banner + astToString(ast));
console.log(`wrote ${TARGET.pathname}`);
